void gaugeRenderScreen(uint16_t* fb, ScreenContent content)
    {
    // Wrap the caller's raw buffer in a tgx canvas. The Image object is just
    // a view (pointer + dimensions) - constructing one costs nothing.
    tgx::Image<tgx::RGB565> im(fb, SCREEN_LX, SCREEN_LY);
    const Theme t = buildTheme();

    switch (content)
        {
        case SCREEN_OIL_VOLTS:  renderOilVolts (im, t); break;
        case SCREEN_CLT_FUEL:   renderCltFuel  (im, t); break;
        case SCREEN_PSI_LAMBDA: renderPsiLambda(im, t); break;
        default:                im.fillScreen(t.bg);    break;
        }
    }
