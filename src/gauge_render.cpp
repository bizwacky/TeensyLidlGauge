// ---------------------------------------------------------------------------
// Rally CAN Gauge - gauge frame rendering implementation
// ---------------------------------------------------------------------------
// Layout of this file:
//   1. fonts + the theme (semantic colors, resolved once per frame)
//   2. value -> color: mapping alarm verdicts onto readouts
//   3. formatting + validity helpers
//   4. drawing primitives ported from the PC prototype (icons, bars, lambda)
//   5. the three gauge layouts
//   6. the MODE_DEBUG dense layout
//
// THE DESIGN, IN THREE RULES:
//
// (1) Stateless "compose then show", exactly like the LED strip: every call
//     rebuilds the whole frame from g_data. No element remembers what it
//     showed last tick, so there is no stale-pixel state to get wrong. This
//     costs CPU (~a millisecond per frame) but costs almost NO SPI traffic:
//     the display driver diffs the finished frame against what the glass
//     already shows and uploads only the pixels that changed. Redrawing
//     everything is not the same as uploading everything - that split is
//     what makes the whole architecture simple AND fast.
//
// (2) Colors are SEMANTIC, resolved through a per-frame Theme. Draw code
//     never says "blue"; it says t.info ("cold / informational"), and the
//     theme decides what that means: dodger blue by day, amber at night
//     (per the plan, night mode replaces every blue element - blue is the
//     worst color for dark-adapted eyes). One resolve point means night
//     mode can never miss an element.
//
// (3) A readout's color comes from ALARM VERDICTS, never from re-testing
//     values: each readout lists which alarms judge it, in catalog order
//     (= priority order), and wears the color of the first active one -
//     green when none are. Thresholds, hysteresis and persistence all
//     stay in alarms.cpp; if the display disagreed with the alarm system
//     about when "hot" starts, the driver would learn to distrust both.
//
// A dead data source draws as "--" in the dim divider color: a gauge that
// shows a plausible-looking 0 psi teaches panic, and one that freezes a
// stale 56 psi teaches complacency. Absent data must LOOK absent. The
// matching NO CAN / BATT CAN yellow alarm appears in the banner on its own.
// ---------------------------------------------------------------------------

